def create_zip_for_view(selected_image, results_state, file_key, zip_name):
    """Generic helper to zip files of a certain type for the selected view."""
    filtered = [r for r in results_state if r["source_file"] == selected_image]
    if not filtered:
        raise gr.Error("No results found for the selected view.")
        
    paths_to_zip = [r[file_key] for r in filtered if r.get(file_key)]
    if not paths_to_zip:
        raise gr.Error(f"No {file_key.replace('_path', '')} files generated for this view.")
        
    os.makedirs("results_ui", exist_ok=True)
    zip_path = os.path.join("results_ui", zip_name)
    
    with zipfile.ZipFile(zip_path, 'w') as zipf:
        for p in paths_to_zip:
            # Avoid storing absolute paths in zip
            zipf.write(p, os.path.basename(p))
            
    return zip_path

def download_json(selected_image, results_state, format_choice):
    if format_choice == "Zip":
        return create_zip_for_view(selected_image, results_state, "json_path", "results_json.zip")
    else:
        # Merged JSON
        filtered = [r for r in results_state if r["source_file"] == selected_image]
        if not filtered:
            raise gr.Error("No results found for the selected view.")
            
        merged_data = []
        for r in filtered:
            if r.get("json_path") and os.path.exists(r["json_path"]):
                with open(r["json_path"], 'r') as f:
                    merged_data.append(json.load(f))
                    
        os.makedirs("results_ui", exist_ok=True)
        merged_path = os.path.join("results_ui", "merged_results.json")
        with open(merged_path, 'w', encoding='utf-8') as f:
            json.dump(merged_data, f, indent=2)
            
        return merged_path

def download_images(selected_image, results_state):
    return create_zip_for_view(selected_image, results_state, "markup_img_path", "markup_images.zip")

def download_pdfs(selected_image, results_state):
    return create_zip_for_view(selected_image, results_state, "pdf_path", "markup_pdfs.zip")




