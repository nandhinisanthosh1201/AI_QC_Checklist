def process_pdfs(sub_pdf_path, arch_pdf_path, progress=gr.Progress()):
    """Stage 1: Runs the pipeline crop step and extracts metadata."""
    if not sub_pdf_path:
        raise gr.Error("Please upload a Submittal PDF.")
        
    pdf_basename = os.path.splitext(os.path.basename(sub_pdf_path))[0]
    
    # 1. Clear old crop directories for this basename to ensure session isolation
    sub_crop_dir = os.path.join("Submittal_crop", pdf_basename)
    if os.path.exists(sub_crop_dir):
        shutil.rmtree(sub_crop_dir)
        
    # We do not clear Arch_crop fully because it's shared/indexed, but it overwrites.
    
    progress(0.2, desc="Running crop pipeline (this may take a few minutes)...")
    
    # 2. Run Pipeline (Crop & Metadata Extraction)
    if arch_pdf_path is None:
        # Pass a dummy string or rely on the pipeline's failure handling.
        pass
        
    pipeline.run_full_pipeline(sub_pdf_path, arch_pdf_path)
    
    progress(0.8, desc="Loading metadata...")
    
    # 3. Read Metadata generated by pipeline.py
    meta_file = f"submittal_metadata_{pdf_basename}.json"
    if not os.path.exists(meta_file):
        raise gr.Error(f"Failed to generate metadata. Could not find {meta_file}.")
        
    with open(meta_file, 'r', encoding='utf-8') as f:
        metadata = json.load(f)
        
    # Map source_file -> metadata
    crop_map = {os.path.normpath(m.get("source_file")): m for m in metadata if m.get("source_file")}
    
    # Extract choices (the crop paths)
    choices = list(crop_map.keys())
    
    progress(1.0, desc="Complete!")
    return crop_map, gr.update(choices=choices, value=None), "✅ Cropping complete. Please select an image."


def on_image_select(selected_image, crop_map, results_state):
    """Updates the UI when a user selects a cropped image."""
    if not selected_image:
        return gr.update(choices=[]), None, []
        
    meta = crop_map.get(os.path.normpath(selected_image), {})
    view_type = str(meta.get("view_type", "")).upper()
    view_name = str(meta.get("view_name", "")).upper()
    
    # Filter rules based on view_type or view_name
    applicable_rules = []
    for r in GLOBAL_RULES:
        views_to_check = [v.upper() for v in r.get("views_need_to_check", [])]
        if view_type in views_to_check or view_name in views_to_check:
            applicable_rules.append(r)
        else:
            # Fallback partial matching
            for rv in views_to_check:
                if view_name.startswith(rv):
                    applicable_rules.append(r)
                    break
                    
    # Format for Dropdown: (Display Name, Value)
    rule_choices = [(f"{r.get('rule_id')} - {r.get('rule_name', 'Unnamed')}", r.get("rule_id")) for r in applicable_rules]
    
    # Filter results table to ONLY show results for the currently selected view
    filtered_results = [res for res in results_state if res["source_file"] == selected_image]
    
    # Table data format
    table_data = [
        [r["rule_id"], r["rule_name"], r.get("view_id", "Unknown"), r["view_name"], r["view_type"], r["status"], r["confidence"], r["reasoning"]] 
        for r in filtered_results
    ]
    
    # Determine which image to show in Visualizer
    display_image = selected_image
    # If there's a markup image from the latest validation run on this view, show it
    for r in reversed(filtered_results):
        if r.get("markup_img_path") and os.path.exists(r["markup_img_path"]):
            display_image = r["markup_img_path"]
            break
            
    return gr.update(choices=rule_choices, value=None), display_image, table_data


def apply_validation(selected_rules, selected_image, crop_map, results_state, progress=gr.Progress()):
    """Stage 2: Runs validator on selected rule(s) for the selected image."""
    if not selected_image:
        raise gr.Error("Please select an image first.")
    if not selected_rules:
        raise gr.Error("Please select at least one rule to validate.")
        
    # Ensure selected_rules is a list
    if not isinstance(selected_rules, list):
        selected_rules = [selected_rules]
        
    meta = crop_map.get(os.path.normpath(selected_image), {})
    arch_ref = meta.get("arch_ref", "NA")
    
    # Construct expected arch_crop_path
    arch_crop_path = "NA"
    if arch_ref and arch_ref != "NA" and "/" in arch_ref:
        parts = arch_ref.split("/")
        dr_num = parts[0].strip()
        sh_name = parts[1].strip()
        expected_arch_crop = os.path.join("Arch_crop", sh_name, f"{sh_name}_{dr_num}.png")
        if os.path.exists(expected_arch_crop):
            arch_crop_path = expected_arch_crop
            
    # Session output directory for this run
    session_id = str(int(time.time()))
    output_dir = os.path.join("results_ui", session_id)
    os.makedirs(output_dir, exist_ok=True)
    
    # Run validation for each selected rule
    for idx, rule_id in enumerate(selected_rules):
        rule = next((r for r in GLOBAL_RULES if r.get("rule_id") == rule_id), None)
        if not rule:
            print(f"Rule {rule_id} not found. Skipping.")
            continue
            
        progress((idx) / len(selected_rules), desc=f"Validating Rule: {rule_id}...")
        
        req_sources = [r.lower() for r in rule.get("required_sources", [])]
        requires_arch = any("arch" in r or "architectural drawing" in r for r in req_sources)
        
        # Call the backend validator
        if requires_arch:
            validator.run_pipeline(selected_image, arch_crop_path, rule, output_dir, arch_ref)
        else:
            import submittal
            submittal.run_pipeline_single_rule(selected_image, rule, output_dir, cached_views=None)
            
        sub_base = os.path.splitext(os.path.basename(selected_image))[0]
        rule_base = rule.get("rule_id", "UnknownRule")
        
        result_json_path = os.path.join(output_dir, f"{rule_base}_{sub_base}_result.json")
        markup_img_path = os.path.join(output_dir, f"{rule_base}_{sub_base}_markup.jpg")
        markup_pdf_path = os.path.join(output_dir, f"{rule_base}_{sub_base}_markup.pdf")
        
        # Parse result
        new_result = {
            "source_file": selected_image,
            "rule_id": rule_base,
            "rule_name": rule.get("rule_name", "Unknown Rule"),
            "view_id": "Unknown",
            "view_name": meta.get("view_name", "Unknown"),
            "view_type": meta.get("view_type", "Unknown"),
            "status": "ERROR",
            "confidence": 0.0,
            "reasoning": "Failed to run or no output.",
            "markup_img_path": markup_img_path if os.path.exists(markup_img_path) else None,
            "json_path": result_json_path if os.path.exists(result_json_path) else None,
            "pdf_path": markup_pdf_path if os.path.exists(markup_pdf_path) else None
        }
        
        if os.path.exists(result_json_path):
            try:
                with open(result_json_path, 'r', encoding='utf-8') as f:
                    res_data = json.load(f)
                    new_result["status"] = res_data.get("sheet_status", "UNKNOWN")
                    vr = res_data.get("view_results", [{}])[0]
                    new_result["view_id"] = vr.get("view_id", "Unknown")
                    new_result["confidence"] = vr.get("confidence_score", 0.0)
                    new_result["reasoning"] = vr.get("reasoning", "")
            except Exception as e:
                new_result["reasoning"] = f"Error parsing result: {e}"
                
        results_state.append(new_result)
        
    progress(1.0, desc="Validation Complete!")
    
    # Refresh the UI for the currently selected image
    _, display_image, table_data = on_image_select(selected_image, crop_map, results_state)
    return results_state, display_image, table_data


