def load_all_rules():
    """Loads all rule JSONs from the rules/ directory."""
    rule_files = glob.glob(os.path.join("rules", "*.json"))
    rules = []
    for rf in rule_files:
        try:
            with open(rf, 'r', encoding='utf-8') as f:
                data = json.load(f)
                if isinstance(data, list):
                    rules.extend(data)
                else:
                    rules.append(data)
        except Exception as e:
            print(f"Error loading rule {rf}: {e}")
    return rules

GLOBAL_RULES = load_all_rules()


